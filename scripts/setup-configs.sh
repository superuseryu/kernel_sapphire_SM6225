#!/usr/bin/env bash
# setup-configs.sh — inject kernel configs into defconfig
# env: KSU_TYPE, SOURCE_TYPE, DEFCONFIG (full path), KERNEL_DIR
set -e

: "${KSU_TYPE:?}"
: "${SOURCE_TYPE:?}"
: "${DEFCONFIG:?}"
: "${KERNEL_DIR:?}"

CF="$DEFCONFIG"

# Base cleanup
sed -i 's/ cgroup_disable=pressure//'                    "$CF"
sed -i 's/kvm-arm\.mode=protected/kvm-arm.mode=none/' "$CF"
sed -i 's/CONFIG_CMDLINE="/&slub_debug=- page_owner=off noirqdebug mitigations=off /' "$CF"
sed -i 's/kasan\.stacktrace=off/kasan=off/'               "$CF"
sed -i 's/CONFIG_CMDLINE="\(.*\)"/CONFIG_CMDLINE="\1 transparent_hugepage=madvise audit=0 rcu_nocbs=0-3 loglevel=3 silent_boot.mode=silent log_buf_len=2M cpuidle.governor=teo"/' "$CF"

# Strip symbols already in base defconfig to avoid "reassigning" warnings
for SYM in WLAN_VENDOR_ATH \
           FAIR_GROUP_SCHED CFS_BANDWIDTH \
           PID_NS DEBUG_KINFO \
           NET_SCH_CODEL NET_SCH_FQ_CODEL UBSAN NET_SCH_DEFAULT DEFAULT_NET_SCH DEFAULT_NET_SCH_FQ_CODEL \
           LRU_GEN LRU_GEN_ENABLED NET_SCH_FQ DEBUG_MEMORY_INIT PRINTK_CALLER \
           ZRAM_DEF_COMP_LZORLE ZRAM_DEF_COMP_ZSTD ZRAM_DEF_COMP_LZ4 ZRAM_DEF_COMP_LZO ZRAM_DEF_COMP \
           SCHED_WALT SCHED_WALT_DEBUG CPU_FREQ_GOV_SCHEDUTIL CPU_FREQ_DEFAULT_GOV_SCHEDUTIL CPU_FREQ_GOV_VORPAL CPU_FREQ_DEFAULT_GOV_VORPAL \
           TCP_CONG_ADVANCED TCP_CONG_BBR TCP_CONG_BBR3 TCP_CONG_WESTWOOD DEFAULT_TCP_CONG \
		   NET_SCH_DEFAULT DEFAULT_NET_SCH; do
  sed -i "/^CONFIG_${SYM}[= ]/d; /^# CONFIG_${SYM} /d" "$CF"
done

# Common configs (all variants)
cat >> "$CF" << 'EOF'
CONFIG_CPU_FREQ_GOV_SCHEDUTIL=y
CONFIG_CPU_FREQ_DEFAULT_GOV_SCHEDUTIL=y
# CONFIG_SCHED_WALT is not set
# CONFIG_SCHED_WALT_DEBUG is not set
CONFIG_TCP_CONG_ADVANCED=y
# CONFIG_TCP_CONG_BBR is not set
CONFIG_TCP_CONG_BBR3=y
CONFIG_TCP_CONG_WESTWOOD=y
# CONFIG_TCP_CONG_BIC is not set
# CONFIG_TCP_CONG_HTCP is not set
CONFIG_DEFAULT_TCP_CONG="bbr3"
CONFIG_NET_SCH_FQ=y
# CONFIG_NET_SCH_FQ_CODEL is not set
CONFIG_NET_SCH_CAKE=y
CONFIG_NET_SCH_PIE=y
CONFIG_NET_SCH_DEFAULT=y
CONFIG_DEFAULT_FQ=y
CONFIG_DEFAULT_NET_SCH="fq"
# CONFIG_IOSCHED_BFQ is not set
# CONFIG_BFQ_GROUP_IOSCHED is not set
CONFIG_MQ_IOSCHED_DEADLINE=y
CONFIG_DEFAULT_MQ_IOSCHED="mq-deadline"
CONFIG_DEFAULT_DEADLINE=y
CONFIG_ZRAM=m
CONFIG_ZSMALLOC=m
CONFIG_ZRAM_WRITEBACK=y
CONFIG_ZRAM_MEMORY_TRACKING=y
# CONFIG_ZRAM_DEF_COMP_LZORLE is not set
# CONFIG_ZRAM_DEF_COMP_ZSTD is not set
CONFIG_ZRAM_DEF_COMP_LZ4=y
# CONFIG_ZRAM_DEF_COMP_LZO is not set
CONFIG_ZRAM_DEF_COMP="lz4"
CONFIG_ZRAM_MULTI_COMP=y
CONFIG_LRU_GEN=y
CONFIG_LRU_GEN_ENABLED=y
CONFIG_LRU_GEN_WALKS_MMU=y
# CONFIG_HZ_100 is not set
# CONFIG_HZ_250 is not set
CONFIG_HZ_300=y
# CONFIG_HZ_1000 is not set
CONFIG_HZ=300
CONFIG_FRAME_WARN=0
CONFIG_WQ_POWER_EFFICIENT_DEFAULT=y
# CONFIG_SLUB_DEBUG_ON is not set
# CONFIG_SLUB_STATS is not set
# CONFIG_DEBUG_LIST is not set
# CONFIG_DEBUG_KINFO is not set
# CONFIG_DEBUG_MEMORY_INIT is not set
# CONFIG_RCU_TRACE is not set
# CONFIG_PRINTK_CALLER is not set
# CONFIG_DEBUG_FS is not set
# CONFIG_DEBUG_MISC is not set
# CONFIG_UBSAN is not set
CONFIG_DISABLE_TRACE_PRINTK=y
# CONFIG_F2FS_IOSTAT is not set
CONFIG_NTSYNC=y
CONFIG_SCHED_BORE=y
CONFIG_SCHED_PREFER_SILVER=y
# CONFIG_RCU_LAZY_DEFAULT_OFF is not set
CONFIG_SCHED_CASS=y
CONFIG_MQ_IOSCHED_ADIOS=y
CONFIG_CPU_FREQ_GOV_REFLEX=y
CONFIG_CPU_FREQ_GOV_VORPAL=y
CONFIG_NOMOUNT=y
CONFIG_CPU_IDLE_GOV_NAP=y
CONFIG_UPROBES=y
CONFIG_UPROBE_EVENTS=y
CONFIG_ENCORE_FAS=m
CONFIG_WLAN=y
CONFIG_WLAN_VENDOR_ATH=y
CONFIG_CFG80211=m
CONFIG_MAC80211=m
CONFIG_ATH9K_HTC=m
CONFIG_ATH=m
CONFIG_ATH9K_HW=m
CONFIG_ATH9K_COMMON=m
CONFIG_WLAN_VENDOR_REALTEK=y
CONFIG_RTL8188GU=m
CONFIG_CGROUP_PIDS=y
CONFIG_SUSPEND_SKIP_SYNC=y
CONFIG_PM_WAKELOCKS_GC=y
CONFIG_POWERSUSPEND=y
CONFIG_MACVLAN=y
CONFIG_USER_NS=y
CONFIG_KFENCE_DEFERRABLE=y
# CONFIG_LOCALVERSION_AUTO is not set
CONFIG_BOEFFLA_WL_BLOCKER=y
EOF

# KSU-Next
if [ "$KSU_TYPE" = "ksun" ]; then
cat >> "$CF" << 'EOF'
CONFIG_KSU=y
CONFIG_KSU_SUSFS=y
CONFIG_KSU_SUSFS_SUS_MAP=y
CONFIG_KSU_SUSFS_SUS_PATH=y
CONFIG_KSU_SUSFS_SUS_MOUNT=y
CONFIG_KSU_SUSFS_SUS_KSTAT=y
CONFIG_KSU_SUSFS_SPOOF_UNAME=y
CONFIG_KSU_SUSFS_SUS_OVERLAYFS=n
CONFIG_KSU_SUSFS_AUTO_ADD_SUS_KSU_DEFAULT_MOUNT=y
CONFIG_KSU_SUSFS_AUTO_ADD_SUS_BIND_MOUNT=y
CONFIG_KSU_SUSFS_TRY_UMOUNT=y
CONFIG_KSU_SUSFS_AUTO_ADD_TRY_UMOUNT_FOR_BIND_MOUNT=y
CONFIG_KSU_SUSFS_ENABLE_LOG=y
CONFIG_KSU_SUSFS_HIDE_KSU_SUSFS_SYMBOLS=y
CONFIG_KSU_SUSFS_SPOOF_CMDLINE_OR_BOOTCONFIG=y
CONFIG_KSU_SUSFS_OPEN_REDIRECT=y
CONFIG_KSU_SUSFS_SUS_SU=y
CONFIG_BBG=y
EOF

# SukiSU-Ultra
elif [ "$KSU_TYPE" = "sksu" ]; then
cat >> "$CF" << 'EOF'
CONFIG_KSU=y
CONFIG_KPM=y
CONFIG_KSU_SUSFS=y
CONFIG_KSU_SUSFS_SUS_MAP=y
CONFIG_KSU_SUSFS_SUS_PATH=y
CONFIG_KSU_SUSFS_SUS_MOUNT=y
CONFIG_KSU_SUSFS_SUS_KSTAT=y
CONFIG_KSU_SUSFS_SPOOF_UNAME=y
CONFIG_KSU_SUSFS_SUS_OVERLAYFS=n
CONFIG_KSU_SUSFS_AUTO_ADD_SUS_KSU_DEFAULT_MOUNT=y
CONFIG_KSU_SUSFS_AUTO_ADD_SUS_BIND_MOUNT=y
CONFIG_KSU_SUSFS_TRY_UMOUNT=y
CONFIG_KSU_SUSFS_AUTO_ADD_TRY_UMOUNT_FOR_BIND_MOUNT=y
CONFIG_KSU_SUSFS_ENABLE_LOG=y
CONFIG_KSU_SUSFS_HIDE_KSU_SUSFS_SYMBOLS=y
CONFIG_KSU_SUSFS_SPOOF_CMDLINE_OR_BOOTCONFIG=y
CONFIG_KSU_SUSFS_OPEN_REDIRECT=y
CONFIG_KSU_SUSFS_SUS_SU=y
EOF

# NoKSU — no extras, common configs above apply
# (only common configs above apply — nothing extra here)
fi

# GKI-only configs
if [ "$SOURCE_TYPE" = "gki" ]; then
cat >> "$CF" << 'EOF'
CONFIG_FAIR_GROUP_SCHED=y
CONFIG_CFS_BANDWIDTH=y
EOF
fi

echo "[OK] Configs written for KSU_TYPE=$KSU_TYPE SOURCE_TYPE=$SOURCE_TYPE"
